#!/usr/bin/env node
/**
 * Regenerates the shipped Work API client from the R0a contract.
 *
 * C07(b) requires the frontend call layer to ship from a regenerated client rather than by hand.
 * The generator itself is the one the contract gate already uses (generate-client.mjs in the design
 * asset directory): it renders a dependency-free client whose paths, methods, CSRF requirement,
 * stream flag and success schema all come from r0a-openapi-v1.yaml.
 *
 * Three files land in the app:
 *   r0a-client.mjs        - the generated runtime, copied verbatim
 *   r0a-api-types.d.ts    - the openapi-typescript output, copied verbatim, so the client's JSDoc
 *                           `import('./r0a-api-types')` references resolve next to it
 *   r0a-client.d.mts      - declarations rendered from the same operation table, because the app is
 *                           compiled with strict TypeScript and tsconfig.app.json does not set
 *                           allowJs; without it `./generated/r0a-client.mjs` has no type
 *
 * `--check` compares all three against what the contract currently produces and exits 1 on drift;
 * it is wired into `npm test`, which CI runs, so a hand-edited copy or an unregenerated contract
 * fails the build instead of silently shipping.
 */

import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

import {
  SPEC_PATH,
  parseOperations,
  renderClient,
} from '../../../docs/plan/assets/work-r0a-design-2026-10-25/generate-client.mjs'

const HERE = path.dirname(fileURLToPath(import.meta.url))
const OUT_DIR = path.join(HERE, '..', 'src', 'features', 'work', 'r0a', 'api', 'generated')
const TYPES_SOURCE = path.join(
  HERE,
  '..',
  '..',
  '..',
  'docs',
  'plan',
  'assets',
  'work-r0a-design-2026-10-25',
  'r0a-api-types.d.ts',
)
const RUNTIME_FILE = path.join(OUT_DIR, 'r0a-client.mjs')
const TYPES_FILE = path.join(OUT_DIR, 'r0a-api-types.d.ts')
const DECLARATION_FILE = path.join(OUT_DIR, 'r0a-client.d.mts')

/** Mirrors primitiveFor in generate-client.mjs: the contract's only numeric params. */
function primitiveFor(name) {
  return name === 'versionNo' || name === 'limit' ? 'number' : 'string'
}

function paramType(name) {
  return primitiveFor(name)
}

function responseOf(operation) {
  if (operation.stream) return 'WorkStreamResponse'
  if (operation.successSchema) {
    return `WorkResponse<Schemas[${JSON.stringify(operation.successSchema)}]>`
  }
  if (operation.successContentType?.startsWith('text/')) return 'WorkResponse<string>'
  return 'WorkResponse<unknown>'
}

function paramsOf(operation) {
  const fields = []
  for (const name of operation.pathParams) {
    fields.push(`${JSON.stringify(name)}: ${paramType(name)}`)
  }
  for (const name of operation.queryParams) {
    fields.push(`${JSON.stringify(name)}?: ${paramType(name)}`)
  }
  for (const name of operation.headerParams) {
    fields.push(`${JSON.stringify(name)}?: string`)
  }
  if (operation.hasBody) {
    const body = operation.requestSchema
      ? `Schemas[${JSON.stringify(operation.requestSchema)}]`
      : 'Record<string, unknown>'
    fields.push(`body${operation.requestRequired ? '' : '?'}: ${body}`)
  }
  fields.push('signal?: AbortSignal')
  const required =
    operation.hasBody ||
    operation.pathParams.length > 0 ||
    operation.queryParams.length > 0 ||
    operation.headerParams.length > 0
  const inner = fields.join('; ')
  return required ? `(params: { ${inner} })` : `(params?: { ${inner} })`
}

export function renderDeclarations(operations) {
  const methods = operations.map((operation) => {
    const summary = operation.summary.replace(/\*\//g, '*\\/')
    return `  /** ${operation.method} ${operation.path} - ${summary} */\n  ${
      operation.operationId
    }${paramsOf(operation)}: Promise<${responseOf(operation)}>;`
  })
  const names = operations.map((operation) => JSON.stringify(operation.operationId))
  return `/**
 * AUTO-GENERATED by scripts/gen-work-api.mjs from r0a-openapi-v1.yaml.
 * Do not edit by hand. Run: npm run gen:work-api
 * CI runs npm test, which checks this file against the contract.
 */

import type { components } from './r0a-api-types'

export type WorkApiEnvelope = {
  code: string
  message?: string
  retryable?: boolean
  correlation_id?: string
  current_revision?: number | null
  recovery_action?: string | null
}

type Schemas = components['schemas']

export type WorkResponse<T> = {
  status: number
  headers: Record<string, string>
  requestId: string | null
  data: T
}

export type WorkStreamResponse = {
  status: number
  headers: Record<string, string>
  events: AsyncGenerator<{
    id: string | null
    event: string | null
    data: unknown
    rawData: string
  }>
}

export type WorkOperation = {
  method: string
  path: string
  operationId: string
  summary: string
  pathParams: string[]
  queryParams: string[]
  headerParams: string[]
  requiresCsrf: boolean
  requestSchema: string | null
  requestRequired: boolean
  successStatus: number
  successSchema: string | null
  successContentType: string | null
  stream: boolean
  hasBody: boolean
}

export class WorkApiError extends Error {
  name: 'WorkApiError'
  status: number
  code: string
  requestId: string | null
  data: unknown
  constructor(details: {
    status: number
    code: string
    message: string
    requestId?: string | null
    data?: unknown
  })
}

export type WorkClientConfig = {
  baseUrl?: string
  fetchImpl?: typeof fetch
  credentials?: RequestCredentials
  cookie?: string | null
  csrfToken?: string | null
  getCsrfToken?: () => string | null | undefined | Promise<string | null | undefined>
  refreshCsrfToken?: () => string | null | undefined | Promise<string | null | undefined>
  headers?: Record<string, string>
}

export type WorkClient = {
${methods.join('\n')}
}

/** The operation table the client is built from, in contract order. */
export declare const OPERATIONS: ReadonlyArray<WorkOperation> & readonly [
${names.map((name) => `  ${name}`).join(',\n')}
]

export declare function createWorkClient(config?: WorkClientConfig): WorkClient

/** Parses an SSE byte stream into frames; comment frames are ignored. */
export declare function readSse(
  body: ReadableStream<Uint8Array> | null
): AsyncGenerator<{
  id: string | null
  event: string | null
  data: unknown
  rawData: string
}>
`
}

function outputs() {
  const yamlText = fs.readFileSync(SPEC_PATH, 'utf8')
  const operations = parseOperations(yamlText)
  return [
    { file: RUNTIME_FILE, text: renderClient(yamlText, operations) },
    { file: TYPES_FILE, text: fs.readFileSync(TYPES_SOURCE, 'utf8') },
    { file: DECLARATION_FILE, text: renderDeclarations(operations) },
  ]
}

function main() {
  const check = process.argv.includes('--check')
  const files = outputs()
  if (check) {
    for (const { file, text } of files) {
      const current = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : ''
      if (current !== text) {
        console.error(
          `${path.relative(path.join(HERE, '..'), file)} is out of date with ` +
            `r0a-openapi-v1.yaml. Run: npm run gen:work-api`
        )
        process.exit(1)
      }
    }
    console.log(`work api client up to date (${files.length} generated files)`)
    return
  }
  fs.mkdirSync(OUT_DIR, { recursive: true })
  for (const { file, text } of files) {
    fs.writeFileSync(file, text, 'utf8')
  }
  console.log(`wrote ${files.map((entry) => path.basename(entry.file)).join(', ')}`)
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  main()
}
