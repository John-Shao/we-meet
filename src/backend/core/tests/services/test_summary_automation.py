def start(user, record):
    """No job is generated by the consent command itself."""
    return control_automation(
        record.pk, user, uuid.uuid4(), {"enabled": True, "expected_revision": 0}
    )[1]


def test_no_implicit_consent_and_flag_cannot_start_any_record(settings):
    user, _, _, record = live_note()
    assert tick_automations() == 0
    assert not record.processing_jobs.exists()
    settings.MEETING_SUMMARY_AUTOMATION_ENABLED = False
    with pytest.raises(RecordConflict):
        start(user, record)
    assert not models.MeetingSummaryAutomation.objects.exists()


def test_toggle_replay_returns_historic_result_without_reenabling():
    user, _, _, record = live_note()
    key = uuid.uuid4()
    body = {"enabled": True, "expected_revision": 0}
    first, automation, _ = control_automation(record.pk, user, key, body)
    control_automation(
        record.pk, user, uuid.uuid4(), {"enabled": False, "expected_revision": 1}
    )
    replay, current, repeated = control_automation(record.pk, user, key, body)
    assert repeated and replay.pk == first.pk
    assert replay.result["enabled"] is True
    assert current.enabled is False and current.revision == 2
    with pytest.raises(RecordConflict):
        control_automation(record.pk, user, key, {**body, "enabled": False})
    assert tick_automation(automation.pk) is False


def test_scheduler_creates_one_intent_and_frozen_control_fence():
    user, _, _, record = live_note()
    automation = start(user, record)
    assert tick_automation(automation.pk) is True
    assert tick_automation(automation.pk) is False
    job = record.processing_jobs.get()
    assert job.configuration["stage"] == "realtime"
    assert job.configuration["automation_id"] == str(automation.pk)
    assert job.configuration["automation_revision"] == 1
    assert job.user_requests.count() == 1
    assert complete(job)
    assert tick_automation(automation.pk) is False
    assert record.processing_jobs.count() == 1


@pytest.mark.parametrize("stop", ["toggle", "access", "flag"])
def test_stop_or_revocation_during_provider_call_never_publishes(stop, settings):
    user, session, _, record = live_note()
    automation = start(user, record)
    tick_automation(automation.pk)
    job = record.processing_jobs.get()

    def reply(**kwargs):
        if stop == "toggle":
            control_automation(
                record.pk,
                user,
                uuid.uuid4(),
                {"enabled": False, "expected_revision": 1},
            )
        elif stop == "access":
            models.ResourceAccess.objects.filter(
                resource=session.room, user=user
            ).delete()
        else:
            settings.MEETING_SUMMARY_AUTOMATION_ENABLED = False
        return output(job)

    assert complete(job, reply) is None
    assert not record.summary_versions.exists()
    job.refresh_from_db()
    assert job.status == "canceled"


def test_quick_then_final_run_without_browser_and_do_not_repeat_completed_cost():
    user, _, _, record = online_note()
    automation = start(user, record)
    assert tick_automation(automation.pk)
    quick = record.processing_jobs.get()
    assert quick.configuration["stage"] == "quick"
    assert complete(quick)
    assert tick_automation(automation.pk)
    final = record.processing_jobs.order_by("-generation").first()
    assert final.configuration["stage"] == "final"
    assert complete(final)
    for _ in range(3):
        assert tick_automation(automation.pk) is False
    automation.refresh_from_db()
    assert automation.state == "completed"
    assert record.summary_versions.count() == 2


def test_failed_output_stays_visible_and_no_paid_auto_retry():
    user, _, _, record = live_note()
