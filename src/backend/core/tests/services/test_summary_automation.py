def test_stop_available_when_rollout_disabled_and_read_share_cannot_toggle(settings):
    user, _, _, record = live_note()
    automation = start(user, record)
    reader = UserFactory()
    models.MeetingRecordAccess.objects.create(
        record=record, user=reader, read_summary=True
    )
    url = f"/api/v1.0/meeting-records/{record.pk}/summary-automation/"
    assert client_for(reader).get(url).json()["can_control"] is False
    with pytest.raises(SummaryRequestDenied):
        control_automation(
            record.pk, reader, uuid.uuid4(), {"enabled": False, "expected_revision": 1}
        )
    settings.MEETING_SUMMARY_AUTOMATION_ENABLED = False
    response = client_for(user).post(
        url,
        {"enabled": False, "expected_revision": 1},
        format="json",
        HTTP_IDEMPOTENCY_KEY=str(uuid.uuid4()),
    )
    assert (
        response.status_code == 200 and response.json()["current"]["enabled"] is False
    )
    automation.refresh_from_db()
    assert automation.state == "off"


def test_revoked_controller_disables_and_outbox_failure_is_recoverable(
    django_capture_on_commit_callbacks,
):
    user, session, _, record = live_note()
    automation = start(user, record)
    with patch("meet.celery_app.app.send_task", side_effect=RuntimeError("redacted")):
        with django_capture_on_commit_callbacks(execute=True):
            tick_automation(automation.pk)
    intent = record.summary_requests.get()
    intent.refresh_from_db()
    assert intent.dispatch_state == "pending"
    models.MeetingSummaryRequest.objects.filter(pk=intent.pk).update(
        dispatch_attempted_at=timezone.now() - timedelta(seconds=31)
    )
    assert tick_automations() == 0
    intent.refresh_from_db()
    assert intent.dispatch_state == "sent"
    models.ResourceAccess.objects.filter(resource=session.room, user=user).delete()
    assert tick_automation(automation.pk) is False
    automation.refresh_from_db()
    assert not automation.enabled and automation.error_code == "permission_revoked"


def test_lost_queue_message_resends_same_attempt_once_per_interval(
    django_capture_on_commit_callbacks,
):
    user, _, _, record = live_note()
    automation = start(user, record)
    with django_capture_on_commit_callbacks(execute=True):
        tick_automation(automation.pk)
    intent = record.summary_requests.get()
    job = intent.job
    models.MeetingSummaryRequest.objects.filter(pk=intent.pk).update(
        dispatch_attempted_at=timezone.now() - timedelta(seconds=31)
    )
    with patch("meet.celery_app.app.send_task") as send:
        with django_capture_on_commit_callbacks(execute=True):
            assert tick_automation(automation.pk) is False
        with django_capture_on_commit_callbacks(execute=True):
            assert tick_automation(automation.pk) is False
        assert send.call_count == 1
        assert send.call_args.kwargs["args"] == [str(job.pk), 1]
    assert record.processing_jobs.count() == record.summary_requests.count() == 1


@pytest.mark.django_db(transaction=True)
def test_two_schedulers_serialize_one_intent():
    user, _, _, record = live_note()
    automation = start(user, record)
    barrier = Barrier(2)

    def run():
        close_old_connections()
        try:
            barrier.wait(timeout=5)
            return tick_automation(automation.pk)
        finally:
            close_old_connections()

    with ThreadPoolExecutor(max_workers=2) as pool:
        results = list(pool.map(lambda _: run(), range(2)))
    assert sorted(results) == [False, True]
    assert record.processing_jobs.count() == record.summary_requests.count() == 1
